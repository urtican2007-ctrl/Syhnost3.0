namespace Syhnost
{
    /// <summary>
    /// Базовый интерфейс для всех сущностей предметной области.
    /// Нужен, чтобы слой доступа к данным мог работать с любой сущностью
    /// одинаково (искать, изменять и удалять объект по идентификатору),
    /// ничего не зная о её конкретных полях.
    /// </summary>
    public interface IDomainObject
    {
        /// <summary>
        /// Уникальный идентификатор объекта (первичный ключ в базе данных).
        /// </summary>
        int Id { get; set; }
    }
}
